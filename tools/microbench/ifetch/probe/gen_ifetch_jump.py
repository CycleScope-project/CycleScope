#!/usr/bin/env python3
"""Generate probes/ifetch_jump.hpp: a chain of M code blocks, each exactly one
128 B line, inside a single asm volatile block.  PERM=1 links block i to
(37*i + 1) % M (full-period affine map, every block visited once); PERM=0
links i -> i+1.  The chain enters at block 0 and leaves to the exit label.

Block layout (8 instructions = 128 B): 6 rotating-register add.u32, one
`@p0 bra` to the chain target, one trailing dead add.u32 the taken branch
skips.  p0 is an always-true predicate on the opaque kernel argument K: an
unconditional bra is jump-threaded away by ptxas, and a bra to the literal
next instruction is removed regardless of predicate, so the branch must skip
an instruction to survive.  Executed mix per block: 6 adds + 1 taken branch
(identical for both PERM values, so the extra cancels in PERM1 - PERM0);
the static block still contains 7 add-class instructions + 1 BRA.

Used by probes/ifetch.cu; the header is gitignored and regenerated by
build.sh."""

import argparse

MS = [16, 64, 256, 1024, 4096]


def chain(m, perm):
    """Return asm lines for the whole chain."""
    # %= gives every emitted copy of this asm block fresh label names
    out = ['"{\\n\\t.reg .pred p<1>;\\n\\t"',
           '"setp.ne.s32 p0, %7, 0;\\n\\t"']

    def target(i):
        t = (37 * i + 1) % m if perm else i + 1
        return "exit" if t == 0 or t == m else str(t)

    for i in range(m):
        out.append(f'"LJ_m{m}_p{perm}_b{i}%=:\\n\\t"')
        for r in range(6):
            a, b, c = (i + r) % 7, (i + r + 1) % 7, (i + r + 2) % 7
            out.append(f'"add.u32 %{a}, %{b}, %{c};\\n\\t"')
        t = target(i)
        tgt = (f"LJ_m{m}_p{perm}_exit%=" if t == "exit"
               else f"LJ_m{m}_p{perm}_b{t}%=")
        out.append(f'"@p0 bra {tgt};\\n\\t"')
        out.append(f'"add.u32 %{i % 7}, %{i % 7}, 1;\\n\\t"')
    out.append(f'"LJ_m{m}_p{perm}_exit%=:\\n\\t"')
    out.append('"}\\n\\t"')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--none", action="store_true",
                    help="declaration only (per-N builds, IFETCH_N: no jump kernels)")
    a = ap.parse_args()
    lines = [
        "// generated by tools/microbench/gen_ifetch_jump.py - do not edit",
        "#pragma once",
        "",
        "template <int M, int PERM> struct IfetchJump;",
        "",
    ]
    for m in ([] if a.none else MS):
        for perm in (0, 1):
            lines.append(f"template <> struct IfetchJump<{m}, {perm}> {{")
            lines.append("  static __device__ __forceinline__ void run(std::uint32_t* r, int kk) {")
            lines.append("    asm volatile(")
            lines += ["      " + l for l in chain(m, perm)]
            ops = ", ".join(f'"+r"(r[{i}])' for i in range(7))
            lines.append(f'      : {ops} : "r"(kk) : "memory");')
            lines.append("  }")
            lines.append("};")
            lines.append("")
    with open(a.out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
