#!/usr/bin/env python3
"""Generate probes/ifetch_bodies.hpp: straight-line bodies of N integer adds
on 8 rotating registers as a single asm volatile block per footprint.

Two predicates (both true at runtime, derived from the opaque kernel argument
K so ptxas cannot evaluate them) alternate on the adds: without them ptxas
folds whole runs of `add.u32 r, r, 1` into a single add/imad.  ptxas still
picks IADD3 / IMAD.IADD / VIADD per instruction; all are single-issue integer
adds and the SASS gate counts them as one class.  The two ISETP instructions
that set the predicates sit inside the clock window (<= 2 extra instructions
against bodies of >= 256).

Used by probes/ifetch.cu; the header is gitignored and regenerated by
build.sh."""

import argparse

NS = [256, 512, 1024, 1280, 1536, 1792, 1856, 1920, 1984, 2048,
      2112, 2176, 2240, 2304, 2432, 2560, 2816, 3072, 4096, 5120,
      6144, 7168, 8192, 10240, 12288, 16384, 32768]

MIX_NS = [512, 1024, 1536, 1792, 2048, 3072, 4096, 8192]

# W=8 and W=16 mix widths run only these footprints (amendment[5]);
# W=4 keeps the full MIX_NS axis.
MIX_NS_WIDE = [1024, 2048, 4096, 8192]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--only-n", type=int, default=0,
                    help="emit only the footprint N (per-N builds, IFETCH_N)")
    a = ap.parse_args()
    ns = [n for n in NS if not a.only_n or n == a.only_n]
    mix_ns = [n for n in MIX_NS if not a.only_n or n == a.only_n]
    lines = [
        "// generated by tools/microbench/gen_ifetch_bodies.py - do not edit",
        "#pragma once",
        "",
        "// Body signature: run(uint32* r, int k) - k is the (opaque) pass count.",
        "template <int N> struct IfetchLine;",
        "",
    ]
    for n in ns:
        lines.append(f"template <> struct IfetchLine<{n}> {{")
        lines.append("  static __device__ __forceinline__ void run(std::uint32_t* r, int kk) {")
        lines.append('    asm volatile("{\\n\\t.reg .pred p<2>;\\n\\t"')
        lines.append('      "setp.ne.s32 p0, %8, 0;\\n\\t"')
        lines.append('      "setp.lt.s32 p1, %8, 100000;\\n\\t"')
        for i in range(n):
            lines.append(f'      "@p{i % 2} add.u32 %{i % 8}, %{i % 8}, 1;\\n\\t"')
        lines.append('      "}\\n\\t"')
        ops = ", ".join(f'"+r"(r[{i}])' for i in range(8))
        lines.append(f'      : {ops} : "r"(kk) : "memory");')
        lines.append("  }")
        lines.append("};")
        lines.append("")
    # k_mix: four byte-distinct bodies per footprint (one code path per
    # warp).  The register rotation order and the predicate phase differ
    # per W so ptxas cannot merge the four blocks into one address range.
    lines.append("template <int N, int W> struct IfetchMix;")
    lines.append("")
    mix_shapes = {n: (16 if n in MIX_NS_WIDE else 4) for n in mix_ns}
    for n in mix_ns:
        for w in range(mix_shapes[n]):
            lines.append(f"template <> struct IfetchMix<{n}, {w}> {{")
            lines.append("  static __device__ __forceinline__ void run(std::uint32_t* r, int kk) {")
            lines.append('    asm volatile("{\\n\\t.reg .pred p<2>;\\n\\t"')
            # distinct but still opaque predicate forms per warp
            lines.append(f'      "setp.ne.s32 p0, %8, {w};\\n\\t"')
            lines.append(f'      "setp.lt.s32 p1, %8, 10000{w};\\n\\t"')
            rot = (w * 3) % 8  # per-warp register rotation offset
            for i in range(n):
                reg = (i + rot) % 8
                pred = (i + w) % 2
                lines.append(f'      "@p{pred} add.u32 %{reg}, %{reg}, 1;\\n\\t"')
            lines.append('      "}\\n\\t"')
            ops = ", ".join(f'"+r"(r[{i}])' for i in range(8))
            lines.append(f'      : {ops} : "r"(kk) : "memory");')
            lines.append("  }")
            lines.append("};")
            lines.append("")
    with open(a.out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
